/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data and group results by specific dimensions.
    - For understanding data distribution across categories.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - GROUP BY, ORDER BY
===============================================================================
*/
--Find total customer by countries
select 
country,
count(customer_key) as total_customers
from gold.dim_customers
group by country
order by total_customers desc;

--Find total customer by gender
select
gender,
count(customer_key) as total_customer
from gold.dim_customers
group by gender
order by total_customer desc;

--Find total product by category
select 
category_id,
count(product_key) as total_product
from gold.dim_products
group by category_id
order by total_product desc;

--What is the average costs in each category
select
category_id,
avg(cost) as avg_cost
from gold.dim_products
group by category_id
order by avg_cost desc;
--what is the total revneue generated for each category?
select 
pr.category_id,
sum(fs.sales_amount) as total_revenue
from gold.fact_sales as fs
left join gold.dim_products as pr
on fs.product_key = pr.product_key
group by pr.category_id
order by total_revenue desc;

--Find total revenue is generated by each customer?
select
c.customer_key,
c.first_name,
c.last_name,
sum(fs.sales_amount) as total_revenue
from gold.dim_customers as c
left join gold.fact_sales as fs
on c.customer_key = fs.customer_key
group by c.customer_key, c.first_name,c.last_name
order by total_revenue desc;

--What is the distribution of sold items across countries?
select
c.country,
sum(fs.quantity) as total_sold_items
from gold.dim_customers as c
left join gold.fact_sales as fs
on c.customer_key = fs.customer_key
group by country
order by total_sold_items desc

--Which country generate more revenue
select 
	c.country,
	sum(fs.sales_amount) as total_sales
from gold.dim_customers as c
left join gold.fact_sales as fs
	on c.customer_key = fs.customer_key
group by c.country
order by total_sales desc;

--What is marital status of order customers
select 
c.marital_status,
count(fs.customer_key) as number_of_orders
from gold.dim_customers as c
left join gold.fact_sales as fs
on c.customer_key = fs.customer_key
group by c.marital_status
order by number_of_orders desc;
